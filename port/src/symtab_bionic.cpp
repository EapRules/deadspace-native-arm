/*
 * The bionic-only imports the generated libc table cannot express.
 *
 * tools/generate_libc.sh builds thunks/libc/generated/impl_tab.h by walking a
 * host glibc header dump, so it can only emit a symbol that (a) glibc also has
 * and (b) has a non-variadic prototype it can reproduce. Everything in this
 * file fails one of those two tests, and the harness sees the result as M2:
 *
 *     unresolved symbol: __atomic_cmpxchg      (bionic-only, no glibc twin)
 *     unresolved symbol: __page_size           (OBJECT, not a function)
 *     unresolved symbol: fcntl                 (variadic)
 *     unresolved symbol: readdir_r             (struct layout differs)
 *     ...
 *
 * Grep impl_tab.h for the names below and every one of them is there, commented
 * out, as THUNK_MISSING or "(TODO impl variadic)". That is the generator saying
 * "I saw this and refused", not "I did not know about it" - so the fix belongs
 * here, in a hand-written override table, and not in the generator.
 */
